def slugify(text: str) -> str:
    normalized = unicodedata.normalize("NFKD", text)
    ascii_text = normalized.encode("ascii", "ignore").decode("ascii")
    return re.sub(r"[^a-z0-9]+", "-", ascii_text.lower()).strip("-") or "item"


def densify(coords: list[list[float]], extra: int = 3) -> list[list[float]]:
    if len(coords) < 2:
        return coords
    out = [list(coords[0])]
    for start, end in zip(coords, coords[1:]):
        for step in range(1, extra + 1):
            t = step / (extra + 1)
            out.append(
                [
                    round(start[0] + (end[0] - start[0]) * t, 5),
                    round(start[1] + (end[1] - start[1]) * t, 5),
                ]
            )
        out.append([round(end[0], 5), round(end[1], 5)])
    return out


