def city_row(item: tuple) -> dict:
    country, cc, name, lat, lng, pop, tier, category, locale, stay, tagline, general, activities, tips = item
    return {
        "id": f"{slugify(name)}-{cc.lower()}",
        "name": name,
        "country": country,
        "cc": cc,
        "lat": lat,
        "lng": lng,
        "pop": pop,
        "tier": "major" if category == "capital" else tier,
        "category": category,
        "locale": locale,
        "stay": stay,
        "tagline": tagline,
        "general": general,
        "activities": activities,
        "tips": tips,
        "photos": [],
    }


def park_row(item: tuple) -> dict:
    name, country, cc, lat, lng, area, bio, pop, stay, category, tagline, summary = item
    return {
        "name": name,
        "country": country,
        "cc": cc,
        "lat": lat,
        "lng": lng,
        "area_km2": area,
        "biodiversity": bio,
        "popularity": pop,
        "stay": stay,
        "category": category,
        "tagline": tagline,
        "summary": summary,
        "photos": [],
    }


def poi_row(item: tuple) -> dict:
    name, country, cc, lat, lng, category, popularity, tagline = item
    return {
        "name": name,
        "country": country,
        "cc": cc,
        "lat": lat,
        "lng": lng,
        "category": category,
        "popularity": popularity,
        "tagline": tagline,
        "photos": [],
    }


def hike_row(item: dict) -> dict:
    return {
        **item,
        "route_type": "hiking",
        "photos": [],
    }


def main() -> None:
    payload = {
        "cities": [city_row(row) for row in CITIES],
        "parks": [park_row(row) for row in PARKS],
        "pois": [poi_row(row) for row in POIS],
        "hikes": [hike_row(row) for row in HIKES],
    }
    OUT.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(
        f"Wrote {OUT.name} with {len(payload['cities'])} cities, "
        f"{len(payload['parks'])} parks, {len(payload['pois'])} POIs, {len(payload['hikes'])} hikes"
    )


if __name__ == "__main__":
    main()
 